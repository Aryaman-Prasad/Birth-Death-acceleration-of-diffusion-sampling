"""Training and checkpoint helpers."""

from pathlib import Path

import torch
from torch import nn

from diffusion.models import make_model
from diffusion.schedulers import make_scheduler


def save_checkpoint(path: str | Path, model: nn.Module, optimizer, epoch: int,
                    config: dict) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    torch.save({"model": model.state_dict(), "optimizer": optimizer.state_dict(),
                "epoch": epoch, "config": config}, path)


def load_checkpoint(path: str | Path, device: torch.device):
    # Checkpoints are generated by this project and include Python config metadata.
    checkpoint = torch.load(path, map_location=device, weights_only=False)
    config = checkpoint["config"]
    model_name = config.get("model", "simple-unet")
    model_args = config.get("model_args")
    if model_args is None:  # Backwards compatibility with the original simple U-Net checkpoints.
        model_args = {"image_channels": config["channels"],
                      "base_channels": config["base_channels"]}
    model = make_model(model_name, **model_args).to(device)
    model.load_state_dict(checkpoint["model"])
    scheduler_name = config.get("scheduler", config.get("beta_schedule", "linear"))
    scheduler = make_scheduler(scheduler_name, config["timesteps"],
                               config["beta_start"], config["beta_end"],
                               config.get("pretrained_model_id"),
                               config.get("pretrained_revision"),
                               config.get("pretrained_scheduler_subfolder")).to(device)
    return model, scheduler, config, checkpoint


def train_epoch(model: nn.Module, scheduler, loader, optimizer,
                device: torch.device, grad_clip: float = 1.0) -> float:
    model.train()
    loss_sum, batches = 0.0, 0
    for batch in loader:
        images = (batch[0] if isinstance(batch, (tuple, list)) else batch).to(device, non_blocking=True)
        optimizer.zero_grad(set_to_none=True)
        loss = scheduler.training_loss(model, images)
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), grad_clip)
        optimizer.step()
        loss_sum += loss.detach().item()
        batches += 1
    if batches == 0:
        raise ValueError("Training loader produced no batches; reduce batch size or add data")
    return loss_sum / batches
