"""
Visualization and Qualitative Result Generation utilities.
Generates:
1. Reverse Denoising Trajectory grids (x_T -> ... -> x_0).
2. 2D Particle Cloud phase plots showing mode formation.
3. Pareto Speed vs. Quality plots (NFE / Latency vs. MMD / Wasserstein).
4. Qualitative comparison grids between baselines and accelerated methods.
"""

import math
import os
from typing import Any, Dict, List, Optional
import matplotlib.pyplot as plt
import numpy as np
import torch
import torchvision.utils as vutils


def plot_2d_distribution_comparison(
    ground_truth: torch.Tensor,
    generated_dict: Dict[str, torch.Tensor],
    save_path: str = "./results/2d_comparison.png",
    title: str = "2D Sampling Quality Comparison"
):
    """
    Plots ground truth points alongside samples generated by various samplers.
    """
    os.makedirs(os.path.dirname(save_path), exist_ok=True)
    n_samplers = len(generated_dict)
    fig, axes = plt.subplots(1, n_samplers + 1, figsize=(4 * (n_samplers + 1), 4), sharex=True, sharey=True)

    gt_np = ground_truth.cpu().numpy()
    axes[0].scatter(gt_np[:, 0], gt_np[:, 1], s=2, alpha=0.3, color="#1f77b4")
    axes[0].set_title("Ground Truth", fontsize=12, fontweight="bold")
    axes[0].set_xlim(-3, 3)
    axes[0].set_ylim(-3, 3)
    axes[0].grid(True, linestyle="--", alpha=0.5)

    colors = ["#ff7f0e", "#2ca02c", "#d62728", "#9467bd", "#8c564b"]
    for i, (sampler_name, samples) in enumerate(generated_dict.items()):
        ax = axes[i + 1]
        samples_np = samples.cpu().numpy()
        color = colors[i % len(colors)]
        ax.scatter(samples_np[:, 0], samples_np[:, 1], s=2, alpha=0.4, color=color)
        ax.set_title(sampler_name, fontsize=12, fontweight="bold")
        ax.grid(True, linestyle="--", alpha=0.5)

    plt.suptitle(title, fontsize=14, y=1.03)
    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches="tight")
    plt.close()


def plot_2d_trajectory(
    intermediates: List[torch.Tensor],
    save_path: str = "./results/2d_trajectory.png",
    num_stages: int = 6
):
    """
    Visualizes the temporal evolution of particles during the reverse diffusion process.
    """
    os.makedirs(os.path.dirname(save_path), exist_ok=True)
    total_steps = len(intermediates)
    indices = np.linspace(0, total_steps - 1, num_stages, dtype=int)

    fig, axes = plt.subplots(1, num_stages, figsize=(3.2 * num_stages, 3.2), sharex=True, sharey=True)

    for col, idx in enumerate(indices):
        pts = intermediates[idx].cpu().numpy()
        ax = axes[col]
        pct = int(100.0 * (1.0 - idx / (total_steps - 1))) if total_steps > 1 else 0
        ax.scatter(pts[:, 0], pts[:, 1], s=3, alpha=0.4, color="#3b528b")
        ax.set_title(f"Step {idx}\n(t ≈ {pct}%)", fontsize=10)
        ax.set_xlim(-3, 3)
        ax.set_ylim(-3, 3)
        ax.grid(True, linestyle="--", alpha=0.4)

    plt.suptitle("Reverse Diffusion Trajectory Evolution ($x_T \\to x_0$)", fontsize=13, y=1.02)
    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches="tight")
    plt.close()


def save_image_grid(
    images: torch.Tensor,
    save_path: str,
    nrow: int = 8,
    normalize: bool = True,
    value_range: tuple = (-1, 1)
):
    """
    Saves a batch of image samples as a formatted grid.
    """
    os.makedirs(os.path.dirname(save_path), exist_ok=True)
    vutils.save_image(images, save_path, nrow=nrow, normalize=normalize, value_range=value_range)


def plot_speed_vs_quality(
    benchmark_results: List[Dict[str, Any]],
    save_path: str = "./results/pareto_frontier.png",
    metric_name: str = "sliced_wasserstein",
    metric_label: str = "Sliced Wasserstein Distance (lower is better)"
):
    """
    Generates Pareto Frontier charts: NFEs & Latency vs. Generation Quality.
    """
    os.makedirs(os.path.dirname(save_path), exist_ok=True)
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))

    names = [r["sampler"] for r in benchmark_results]
    nfes = [r["nfe"] for r in benchmark_results]
    times = [r["inference_time_sec"] for r in benchmark_results]
    metrics = [r[metric_name] for r in benchmark_results]

    # Plot 1: NFEs vs Quality Metric
    ax1.plot(nfes, metrics, marker="o", linewidth=2, markersize=8, color="#2b5c8f")
    for name, x, y in zip(names, nfes, metrics):
        ax1.annotate(name, (x, y), textcoords="offset points", xytext=(0, 8), ha="center", fontsize=9)
    ax1.set_xlabel("Number of Function Evaluations (NFE)", fontsize=11, fontweight="bold")
    ax1.set_ylabel(metric_label, fontsize=11, fontweight="bold")
    ax1.set_title("NFE vs Quality Frontier", fontsize=12, fontweight="bold")
    ax1.grid(True, linestyle="--", alpha=0.6)

    # Plot 2: Inference Time vs Quality Metric
    ax2.plot(times, metrics, marker="s", linewidth=2, markersize=8, color="#d95f02")
    for name, x, y in zip(names, times, metrics):
        ax2.annotate(name, (x, y), textcoords="offset points", xytext=(0, 8), ha="center", fontsize=9)
    ax2.set_xlabel("Total Inference Time (seconds)", fontsize=11, fontweight="bold")
    ax2.set_ylabel(metric_label, fontsize=11, fontweight="bold")
    ax2.set_title("Inference Latency vs Quality Frontier", fontsize=12, fontweight="bold")
    ax2.grid(True, linestyle="--", alpha=0.6)

    plt.suptitle("Sampling Acceleration Pareto Trade-off", fontsize=14, y=1.02)
    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches="tight")
    plt.close()

